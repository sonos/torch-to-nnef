"""Generate `torch_to_nnef/tensor/quant/_iq2_s_grid.py` from tract sources.

Usage: python scripts/gen_iq2_s_grid.py <tract_repo> [<git_ref>]

Reads tract `linalg/src/frame/block_quant/iq2_s_kgrid.rs` at `git_ref`
(default `v0.23.10`) and writes ggml `kgrid_2bit_1024` as a numpy table.
"""

import re
import subprocess
import sys
from pathlib import Path

KGRID_PATH = "linalg/src/frame/block_quant/iq2_s_kgrid.rs"
OUT = (
    Path(__file__).resolve().parent.parent
    / "torch_to_nnef"
    / "tensor"
    / "quant"
    / "_iq2_s_grid.py"
)
PER_LINE = 8


def main():
    tract_repo = sys.argv[1]
    ref = sys.argv[2] if len(sys.argv) > 2 else "v0.23.10"
    src = subprocess.run(
        ["git", "-C", tract_repo, "show", f"{ref}:{KGRID_PATH}"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    body = re.search(r"\[u16; 1024\] = \[(.*?)\];", src, re.S)
    assert body is not None, "KGRID_2BIT_1024 not found"
    values = [
        int(v) for v in body.group(1).replace("\n", " ").split(",") if v.strip()
    ]
    assert len(values) == 1024, len(values)
    lines = [
        '"""ggml `kgrid_2bit_1024`: the 1024 IQ2_S grid points.',
        "",
        "Each entry packs eight 2bit levels (level k at bits 2k..2k+1).",
        f"Generated by `scripts/gen_iq2_s_grid.py` from tract {ref}",
        f"`{KGRID_PATH}`: do not edit.",
        '"""',
        "",
        "import numpy as np",
        "",
        "# fmt: off",
        "KGRID_2BIT_1024 = np.array(",
        "    [",
    ]
    for start in range(0, len(values), PER_LINE):
        chunk = values[start : start + PER_LINE]
        lines.append("        " + ", ".join(str(v) for v in chunk) + ",")
    lines += ["    ],", "    dtype=np.uint16,", ")", "# fmt: on", ""]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
